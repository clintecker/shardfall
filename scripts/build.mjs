#!/usr/bin/env node
// Builds the whole game into single HTML files.
//
//   dist/index.html              a complete page for any static host (or a double-click)
//   dist/shardfall.artifact.html the same game as a Claude artifact fragment: no doctype, no
//                                <html>/<head>/<body>; the artifact host supplies those
//
// No bundler, no minifier, no dependencies: the game is classic scripts that share one global
// scope, so "bundling" is concatenation in the order index.html lists them. The output is
// deterministic (no timestamps), which lets the tests compare builds byte for byte.
import { mkdir, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { fromRoot, loadManifest, read } from './lib/manifest.mjs';

const USE_STRICT = /^\s*'use strict';\s*\n/;

export async function build() {
  const m = await loadManifest();

  const css = (await Promise.all(m.styles.map(s => read(s)))).join('\n').trim();
  if (/<\/style/i.test(css)) throw new Error('CSS contains "</style", which would end the tag');

  const parts = [];
  for (const src of m.sources) {
    const code = await read(src);
    if (!USE_STRICT.test(code)) throw new Error(`${src} must start with 'use strict';`);
    if (/<\/script/i.test(code))
      throw new Error(`${src} contains "</script", which would end the tag`);
    parts.push(`/* ━━ ${src} ━━ */\n${code.replace(USE_STRICT, '').trim()}`);
  }
  const js = `'use strict';\n${parts.join('\n\n')}`;

  const banner = `<!-- ${m.title} ${m.pkg.version} · generated by scripts/build.mjs from src/ · edit the source, not this file -->`;
  const vendorTags = m.vendor.map(u => `<script src="${u}"></script>`).join('\n');
  const fontTags = m.fonts.map(u => `<link rel="stylesheet" href="${u}">`).join('\n');
  const style = `<style>\n${css}\n</style>`;
  const script = `<script>\n${js}\n</script>`;

  const artifact = [
    `<title>${m.title}</title>`,
    '<meta name="claude:viewport-fit-sides" content="cover">',
    banner,
    vendorTags,
    fontTags,
    style,
    m.markup,
    script,
    ''
  ].join('\n');

  const standalone = [
    '<!doctype html>',
    '<html lang="en">',
    '<head>',
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">',
    '<meta name="color-scheme" content="dark">',
    '<meta name="theme-color" content="#0c0e1a">',
    `<title>${m.title}</title>`,
    banner,
    vendorTags,
    fontTags,
    style,
    '</head>',
    '<body>',
    m.markup,
    script,
    '</body>',
    '</html>',
    ''
  ].join('\n');

  return { artifact, standalone, js, css, manifest: m };
}

export async function writeBuild() {
  const out = await build();
  await mkdir(fromRoot('dist'), { recursive: true });
  await writeFile(fromRoot('dist', 'index.html'), out.standalone);
  await writeFile(fromRoot('dist', 'shardfall.artifact.html'), out.artifact);
  return out;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const out = await writeBuild();
  const kb = s => (Buffer.byteLength(s) / 1024).toFixed(1).padStart(7) + ' kB';
  console.log(`dist/index.html              ${kb(out.standalone)}`);
  console.log(`dist/shardfall.artifact.html ${kb(out.artifact)}`);
  console.log(
    `  ${out.manifest.sources.length} source files, ${out.manifest.vendor.length} vendor scripts (CDN)`
  );
}
